"""
Run every method on every input and value variant, compare, and write a report.

``ComparisonStudy`` is configured with lists of inputs, value variants,
methods and the pairs of methods to compare; ``run()`` returns plain records
and ``write_report()`` turns them into Markdown and JSON.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import numpy as np

from anyeg import ScalarField

from .common import CommonGraph
from .inputs import FieldInput, ValueVariant
from .methods import Method
from .metrics import Agreement, compare


@dataclass
class CaseResult:
    input: str
    source: str
    variant: str
    num_points: int
    graphs: Dict[str, CommonGraph] = field(default_factory=dict)
    agreements: List[Agreement] = field(default_factory=list)

    def as_dict(self) -> dict:
        return {
            "input": self.input, "source": self.source, "variant": self.variant,
            "num_points": self.num_points,
            "methods": {k: {"maxima": g.num_maxima, "saddles": g.num_saddles,
                            "maximum_pairs": len(g.maximum_pairs), "seconds": g.seconds,
                            "notes": g.notes} for k, g in self.graphs.items()},
            "agreements": [a.as_dict() for a in self.agreements],
        }


class ComparisonStudy:
    def __init__(self, inputs: Sequence[FieldInput], variants: Sequence[ValueVariant],
                 methods: Sequence[Method], pairs: Sequence[Tuple[str, str]]):
        self.inputs, self.variants, self.methods, self.pairs = inputs, variants, methods, pairs

    def warm_up(self) -> None:
        """One tiny run per method, so CUDA start-up is not counted in the timings."""
        tiny = ScalarField.from_grid(np.random.default_rng(0).random((4, 5, 6)))
        for m in self.methods:
            m.run(tiny)

    def run(self, log=print) -> List[CaseResult]:
        self.warm_up()
        results = []
        for inp in self.inputs:
            base = inp.load()
            for variant in self.variants:
                f = variant.field(base)
                case = CaseResult(inp.name, inp.source, variant.name, f.num_points)
                for m in self.methods:
                    case.graphs[m.name] = m.run(f)
                for a, b in self.pairs:
                    if a in case.graphs and b in case.graphs:
                        case.agreements.append(compare(case.graphs[a], case.graphs[b]))
                log(_one_line(case))
                results.append(case)
        return results


def _one_line(case: CaseResult) -> str:
    counts = ", ".join(f"{k}: {g.num_maxima} max/{g.num_saddles} sad ({g.total_seconds:.2f}s)"
                       for k, g in case.graphs.items())
    return f"{case.input} [{case.variant}] {counts}"


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------
def write_report(results: List[CaseResult], out_dir: Path, variants: Sequence[ValueVariant],
                 method_notes: Dict[str, str]) -> Tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "anyeg_vs_ours.json"
    md_path = out_dir / "anyeg_vs_ours.md"
    json_path.write_text(json.dumps([r.as_dict() for r in results], indent=1, default=float))

    lines = [
        "# AnyEG vs our pipeline: extremum graphs of the same fields",
        "",
        f"Generated by `python3 -m comparison` on {date.today().isoformat()} ({_gpu_name()}). "
        f"Raw numbers: `{json_path.name}`. Findings are discussed in `observations.md`.",
        "",
        "## Methods",
        "",
    ]
    lines += [f"- **{k}**: {v}" for k, v in method_notes.items()]
    lines += ["", "## Value variants", ""]
    lines += [f"- **{v.name}**: {v.description}" for v in variants]
    lines += ["", "## Counts and run time", "",
              "Maxima / saddles / linked pairs of maxima, and wall time in seconds. *core*: for "
              "AnyEG its four GPU modules (maxima, basins, saddles); for ours all of "
              "`extremum_graph()`, which also computes persistence, relief and p* on the CPU. "
              "*total* adds building the neighbour graph (and, for AnyEG, the arcs; for the "
              "original, also starting its process and copying the input to it). Shared GPUs: "
              "timings vary with their load.", ""]
    names = list(results[0].graphs) if results else []
    lines.append("| input | values | N | " + " | ".join(names) + " |")
    lines.append("|---|---|---|" + "---|" * len(names))
    for r in results:
        cells = []
        for n in names:
            g = r.graphs[n]
            cells.append(f"{g.num_maxima:,} / {g.num_saddles:,} / {len(g.maximum_pairs):,}"
                         f"<br>{g.seconds['core']:.3f} s core, {g.total_seconds:.3f} s total")
        lines.append(f"| {r.input} | {r.variant} | {r.num_points:,} | " + " | ".join(cells) + " |")

    lines += ["", "## Agreement", "",
              "Jaccard index of the maxima, saddles and linked pairs of maxima (1 = identical "
              "sets), and the fraction of vertices whose basin has the same maximum. "
              "`only A/B` counts maxima (or pairs) found by one method only.", ""]
    lines.append("| input | values | A | B | maxima J | only A / B | same basin | saddles J "
                 "| pairs J | pairs only A / B |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|")
    for r in results:
        for a in r.agreements:
            lines.append(f"| {r.input} | {r.variant} | {a.a} | {a.b} | {a.maxima_jaccard:.3f} | "
                         f"{a.maxima_only_a:,} / {a.maxima_only_b:,} | {a.region_agreement:.4f} | "
                         f"{a.saddle_jaccard:.3f} | {a.pair_jaccard:.3f} | "
                         f"{a.pairs_only_a:,} / {a.pairs_only_b:,} |")
    md_path.write_text("\n".join(lines) + "\n")
    return md_path, json_path


def _gpu_name() -> str:
    try:
        import torch

        if torch.cuda.is_available():
            return torch.cuda.get_device_name(0)
    except ImportError:
        pass
    return "no GPU"
