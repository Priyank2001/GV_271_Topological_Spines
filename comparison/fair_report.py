"""Markdown and JSON report of ``comparison.fair``."""

from __future__ import annotations

import json
import statistics
from datetime import date
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

from .fair import PROTOCOL, CaseResult, Contender

CORRECTNESS_ROWS = ["AnyEG port", "AnyEG +bundling", "AnyEG uphill arcs (diagnostic)", "Ours",
                    "Ours no loop filter"]


def write_fair_report(results: List[CaseResult], contenders: Sequence[Contender], out_dir: Path,
                      gpu: Optional[str], repeats: int) -> Tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    js = out_dir / "fair_comparison.json"
    md = out_dir / "fair_comparison.md"
    js.write_text(json.dumps({"gpu": _gpu_name(gpu), "repeats": repeats,
                              "cases": [r.as_dict() for r in results]}, indent=1, default=float))
    L: List[str] = []
    L += ["# AnyEG vs our pipeline: a fair comparison", "",
          f"Generated by `python3 -m comparison.fair` on {date.today().isoformat()}: "
          f"{_gpu_name(gpu)}, median of {repeats} timed runs after a warm-up. "
          f"Raw numbers: `{js.name}`. Code: `comparison/fair.py`, `comparison/reference.py`.", "",
          "## What is held equal", "", "| control | how |", "|---|---|"]
    L += [f"| {a} | {b} |" for a, b in PROTOCOL]
    L += ["", "## Contenders", ""]
    L += [f"- **{c.name}** ({c.device}{'' if c.timed else ', not timed'}): {c.description}"
          for c in contenders]

    L += ["", "## 1. Correctness against yardsticks that need neither method", "",
          "* **Merge tree**: the superlevel-set merge tree (0-dim persistence), computed from "
          "the graph and the order alone. Each method's links are replayed from the highest "
          "saddle down; a maximum is *exact* when it dies at the reference saddle. *early* = a "
          "link joins maxima whose components are still apart at that height (a false link); "
          "*late* = a merge saddle is missing. *≥1 %*: pairs with persistence at least 1 % of "
          "the value range. Ours meets this by construction (its saddles are the merge passes).",
          "* **PL-valid**: reported saddles whose upper link has 2+ pieces on the triangulation, "
          "i.e. real critical points of the piecewise-linear field. Only on the 14-neighbour "
          "grid (the 6-neighbour grid is not a triangulation). AnyEG meets this by construction "
          "(its module 4 is this test). For ours, *merge* counts only merge-tree saddles.",
          "", "AnyEG original, the CPU runs and the GPU runs give identical graphs (section 2), "
          "so only one row per algorithm is shown.", ""]
    for nb in _neighborhoods(results):
        L += [f"### {nb} grid", "",
              "| input | N | method | maxima | saddles (3+ max.) | linked pairs | merge tree exact "
              "| early / late | ≥1 % exact | PL-valid saddles |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for r in (x for x in results if x.neighborhood == nb):
            for c in r.contenders:
                if c.name not in CORRECTNESS_ROWS:
                    continue
                f = c.fidelity
                pl = "n/a" if c.pl_valid is None else _frac(*c.pl_valid)
                if c.pl_valid_merge is not None:
                    pl += f"; merge {_frac(*c.pl_valid_merge)}"
                L.append(f"| {r.input} | {r.num_points:,} | {c.name} | {c.maxima:,} | "
                         f"{c.saddles:,} ({c.multi_saddles:,}) | {c.pairs:,} | "
                         f"{f.exact:,}/{f.reference_pairs:,} ({100 * f.exact_fraction:.1f} %) | "
                         f"{f.early:,} / {f.late:,} | "
                         f"{f.significant_exact}/{f.significant_pairs} | {pl} |")
        L.append("")

    L += ["## 2. Agreement on the same graph and order", "",
          "Jaccard index (1 = same set) of maxima, saddle vertices and linked pairs of maxima; "
          "*same basin*: fraction of vertices ascending to the same maximum.", "",
          "| input | grid | A | B | maxima J | same basin | saddles J | pairs J | pairs only A / B |",
          "|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        for a in r.agreements:
            L.append(f"| {r.input} | {r.neighborhood} | {a.a} | {a.b} | {a.maxima_jaccard:.3f} | "
                     f"{a.region_agreement:.4f} | {a.saddle_jaccard:.3f} | {a.pair_jaccard:.3f} | "
                     f"{a.pairs_only_a:,} / {a.pairs_only_b:,} |")

    for device in ("GPU", "CPU"):
        timed = [c for c in contenders if c.timed and c.device == device]
        if not timed:
            continue
        L += ["", f"## 3{'a' if device == 'GPU' else 'b'}. Run time, {device}", "",
              "Median seconds. *detect* = maxima, basins and saddles, host arrays in and out "
              "(the same job for both). *post* = each method's own further work (AnyEG: arcs; "
              "ours: persistence, loop filter, p*), so *total* is not the same job. "
              "*graph* = building the shared neighbour structure once (not in any column)."]
        if device == "GPU":
            L += ["", "AnyEG original: *kernels* = its own CUDA-event times of modules 1-4 "
                  "(no copies, no allocation); *detect* = its whole `compute()` call."]
        else:
            L += ["", "AnyEG has no CPU version: *AnyEG port CPU* is our PyTorch port run on the "
                  "CPU (its module 4 is written for a GPU), so this table says little about "
                  "AnyEG itself."]
        refs = [n for n in (("AnyEG original", "AnyEG port") if device == "GPU"
                            else ("AnyEG port CPU",)) if any(c.name == n for c in timed)]
        L += ["", "| input | grid | N | graph | " + " | ".join(
            f"{c.name} detect | post" for c in timed) + " | " + " | ".join(
            f"Ours / {n} (detect)" for n in refs) + " |",
              "|---|---|---|---|" + "---|---|" * len(timed) + "---|" * len(refs)]
        for r in results:
            by = {c.name: c for c in r.contenders}
            cells = []
            for c in timed:
                t = by[c.name].timing.as_dict()
                det = f"{t['detect']['median']:.4f}"
                if "kernels_only" in t and c.name == "AnyEG original":
                    det += f" (kernels {t['kernels_only']['median']:.4f})"
                cells.append(f"{det} | {t['post']['median']:.4f}")
            ours = by.get("Ours" if device == "GPU" else "Ours CPU")
            ratios = [f"{_med(ours.timing.detect) / _med(by[n].timing.detect):.2f}"
                      if ours and ours.timing else "" for n in refs]
            L.append(f"| {r.input} | {r.neighborhood} | {r.num_points:,} | {r.build_seconds:.3f} | "
                     + " | ".join(cells + ratios) + " |")

    L += ["", "## What cannot be made equal", "",
          "- *post* is different work: AnyEG traces arcs and stops; ours computes persistence, "
          "the loop filter and saturated persistence, which AnyEG does not have.",
          "- AnyEG original runs in its own process (its `compute()` keeps global state). The "
          "process start and file exchange are excluded from *detect* (they are in the JSON as "
          "`process_and_files`), and CUDA is initialised before its clock starts. Its "
          "`compute()` still allocates and copies everything on each call, while PyTorch reuses "
          "cached GPU memory; that is part of how each is built, and is why the port is faster "
          "than the original. Loading its kernels eagerly (`CUDA_MODULE_LOADING=EAGER`) changed "
          "nothing (tested).",
          "- Our torch backend returns to the host between its steps; AnyEG keeps everything on "
          "the GPU inside `compute()`. That is part of each implementation and is counted.",
          "- On the 6-neighbour grid no two neighbours of a vertex are neighbours of each other, "
          "so AnyEG's upper-link test passes every candidate with 2+ higher neighbours: AnyEG is "
          "outside its design there. It is shown to separate the effect of the grid from the "
          "effect of the algorithm.", ""]
    md.write_text("\n".join(L) + "\n")
    return md, js


def _neighborhoods(results: List[CaseResult]) -> List[str]:
    seen: List[str] = []
    for r in results:
        if r.neighborhood not in seen:
            seen.append(r.neighborhood)
    return seen


def _frac(a: int, b: int) -> str:
    return f"{a:,}/{b:,} ({100 * a / b:.0f} %)" if b else "0/0"


def _med(xs) -> float:
    return statistics.median(xs)


def _gpu_name(gpu: Optional[str]) -> str:
    if gpu is None:
        return "no GPU"
    try:
        import torch

        return f"{torch.cuda.get_device_name(gpu)} ({gpu})"
    except Exception:
        return gpu
